import re
from unicodedata import normalize


# The expressions run on lowercase text with punctuation replaced by spaces.
# A suffix such as \w* matches inflected forms within the same word.
TAG_KEYWORDS = {
    "гололёд": (
        r"гололед\w*", r"гололедиц\w*", r"налед\w*", r"ледян\w+ корк\w*",
        r"скользк\w*", r"каток на (?:дорог\w*|тротуар\w*|двор\w*|ступен\w*|лестниц\w*)",
    ),
    "уборка_снега": (
        r"сугроб\w*", r"снежн\w+ (?:занос\w*|завал\w*|вал\w*)",
        r"неубранн\w+ снег\w*", r"(?:не|плохо|редко) (?:чист\w*|убира\w*|расчища\w*)",
        r"не (?:убрал\w*|почистил\w*|расчистил\w*)",
        r"снег\w* не (?:убра\w*|вывез\w*)", r"снег\w* по колено",
    ),
    "сосульки": (
        r"сосуль(?:ка|ки|ке|ку|кой|кою|кам|ками|ках|ек)", r"ледян\w+ глыб\w*", r"(?:лед|снег) с крыш\w*",
        r"сход\w* снега с крыш\w*",
        r"снег\w* (?:пада\w*|упал\w*|сошел\w*) с крыш\w*",
    ),
    "заблокирован_проезд": (
        r"не (?:проехать|проезжа\w*|проед\w*)", r"непроезд\w*",
        r"(?:проезд|дорог\w*) (?:перекры\w*|заблокирован\w*|замело)",
        r"(?:завалило|замело) (?:дорог\w*|проезд\w*)",
        r"(?:машин\w*|автобус\w*|скор\w+) застрял\w*",
    ),
    "заблокирован_проход": (
        r"не (?:пройти|прош\w*)", r"непроходим\w*",
        r"(?:проход|тротуар|вход|выход) (?:перекры\w*|заблокирован\w*|замело)",
        r"(?:завалило|замело) (?:тротуар\w*|вход\w*|выход\w*|дорожк\w*)",
    ),
    "отопление": (
        r"нет отоплени\w*", r"без отоплени\w*",
        r"(?:отключил\w*|отключен\w*) отоплени\w*",
        r"отопление не работа\w*", r"отопление отключ\w*", r"батаре\w+ холодн\w*",
        r"холодн\w+ батаре\w*", r"батаре\w+ не гре\w*", r"прорыв\w* теплотрасс\w*",
    ),
    "замёрзшие_трубы": (
        r"(?:перемерз\w*|замерз\w*) (?:труб\w*|водопровод\w*|канализаци\w*)",
        r"(?:труб\w*|водопровод\w*|канализаци\w*) (?:перемерз\w*|замерз\w*|промерз\w*)",
        r"промерзани\w* (?:труб\w*|водопровод\w*)",
    ),
    "обледенение_проводов": (
        r"обледенени\w* (?:провод\w*|кабел\w*|лини\w*)",
        r"(?:провод\w*|кабел\w*) (?:обледенел\w*|обледеневш\w*)",
        r"(?:обледенел\w*|обледеневш\w*) (?:провод\w*|кабел\w*)",
        r"(?:лед|наледь) на (?:провод\w*|кабел\w*)",
    ),
}


TAG_PATTERNS = {
    tag: re.compile(r"\b(?:" + "|".join(keywords) + r")\b")
    for tag, keywords in TAG_KEYWORDS.items()
}


def analyze_description(description: str) -> tuple[str, ...]:
    text = normalize("NFKC", description).casefold().replace("ё", "е")
    words = " ".join(re.findall(r"[^\W_]+", text))
    return tuple(tag for tag, pattern in TAG_PATTERNS.items() if pattern.search(words))
